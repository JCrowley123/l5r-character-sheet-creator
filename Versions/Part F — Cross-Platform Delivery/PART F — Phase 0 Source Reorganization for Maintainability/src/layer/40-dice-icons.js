/* ============================================================
   PART D — FEATURE 3 · GOLD d10 ROLL BUTTONS

   The sheet's four roll buttons — skill roll, weapon attack, weapon
   damage and Roll Initiative — draw a game-die emoji on a gold pill.
   The floating manual dice-tray button, a few hundred lines away in
   the same document, draws a proper faceted gold d10 as inline SVG.
   This gives the four buttons that same die.

   WHY JAVASCRIPT AND NOT CSS
   Three of the four buttons are generated by the sheet's own script
   whenever the skills or weapons tables re-render, and the sheet's
   script is byte-identical to the trunk by build invariant, so the
   emoji cannot simply be edited out. CSS could paint a die over the
   emoji with a data-URI background, but a data URI is a separate
   document: `var(--gold)` and the sheet's Shippori Mincho face do not
   reach inside it, so the icon would have to hardcode five golds and
   would quietly drift the day the palette is retuned.

   Cloning the live SVG node avoids all of that. The clone resolves the
   same custom properties, uses the same font, and follows the palette
   for free. `#floatingDiceBtn` is the single source of the artwork —
   it is read, never modified.

   The buttons keep their own `title`, and gain a matching `aria-label`:
   the emoji was previously their accessible name, which screen readers
   announce as "game die", and losing it without a replacement would
   leave the name to `title` alone.
   ============================================================ */
(function(){
  'use strict';

  /* Every button that should carry the die. The first three are built by the
     sheet at render time; #btnRollInitiative is in the static markup. */
  var TARGETS = '.dice-btn.sk-roll, .dice-btn.wp-roll-btn, .dice-btn.wp-dmg-btn, #btnRollInitiative';

  var template = null, pending = false;

  function raf(fn){
    if(window.requestAnimationFrame) window.requestAnimationFrame(fn);
    else setTimeout(fn, 16);
  }

  /* Batched to the next frame, racing a short timer in case frames are stalled
     — the same pattern rings-fit.js uses, and for the same reason: a deferred
     carousel page or a background tab can withhold rAF indefinitely. */
  function schedule(){
    if(pending) return;
    pending = true;
    var done = false;
    function fire(){
      if(done) return;
      done = true;
      pending = false;
      sweep();
    }
    raf(fire);
    setTimeout(fire, 60);
  }

  function swap(btn){
    // data-d10 makes this idempotent: appending the icon re-triggers the
    // observer, and the second pass has to find nothing left to do.
    if(btn.getAttribute('data-d10')) return;
    btn.setAttribute('data-d10', '1');

    var label = (btn.getAttribute('title') || '').trim();
    if(label && !btn.getAttribute('aria-label')) btn.setAttribute('aria-label', label);

    var icon = template.cloneNode(true);
    icon.setAttribute('class', 'roll-d10');
    icon.setAttribute('aria-hidden', 'true');
    icon.removeAttribute('id');

    btn.textContent = '';                 // drops the emoji
    btn.appendChild(icon);
  }

  function sweep(){
    var list = document.querySelectorAll(TARGETS);
    for(var i = 0; i < list.length; i++) swap(list[i]);
  }

  function start(){
    // Read-only: this node stays exactly where it is and is never altered.
    template = document.querySelector('#floatingDiceBtn .dice-icon');
    if(!template) return false;

    sweep();

    /* The skills and weapons tables rebuild their rows wholesale, so buttons
       appear long after load. childList only — attribute and text changes are
       not worth waking for, and watching them would make our own aria-label
       write re-enter. */
    if(typeof MutationObserver === 'function'){
      new MutationObserver(schedule).observe(document.body, { childList: true, subtree: true });
    }
    return true;
  }

  function run(){
    try{
      if(start()) return;
      var tries = 0;
      var timer = setInterval(function(){
        if(start() || ++tries > 40) clearInterval(timer);
      }, 50);
    }catch(e){
      /* Failing here leaves every button exactly as the sheet built it — emoji,
         gold pill, working handler. The icon is decoration; it must never be
         able to take a roll button down with it. */
      if(window.console && console.warn) console.warn('[dice-icons] ' + e);
    }
  }

  if(document.readyState === 'loading') document.addEventListener('DOMContentLoaded', run);
  else run();
})();